// 全域輔助函數
function escapeHtml(text) {
    if (!text) return '';
    const map = {
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#039;'
    };
    return String(text).replace(/[&<>"']/g, m => map[m]);
}

// 輸出到全域
if (typeof window !== 'undefined') {
    window.escapeHtml = escapeHtml;
}
